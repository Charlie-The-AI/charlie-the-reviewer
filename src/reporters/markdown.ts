import type { ReviewFinding, ReviewResult, Severity } from "../types/index.js";

const SEVERITY_EMOJI: Record<Severity, string> = {
  critical: "🚨 **Critical**",
  high: "⚠️ **High**",
  medium: "🟡 **Medium**",
  low: "ℹ️ **Low**",
};

export const SUMMARY_MARKER = "<!-- charlie-the-reviewer-summary -->";

export function formatReviewSummaryMarkdown(
  result: ReviewResult,
  options: { unmappedFindings?: ReviewFinding[] } = {}
): string {
  const counts: Record<Severity, number> = {
    critical: 0,
    high: 0,
    medium: 0,
    low: 0,
  };

  for (const f of result.findings) {
    counts[f.severity] = (counts[f.severity] || 0) + 1;
  }

  const statusBadge =
    result.status === "passed"
      ? "✅ **Passed**"
      : result.status === "failed"
        ? "❌ **Failed**"
        : result.status === "incomplete"
          ? "⚠️ **Incomplete**"
          : "⏭️ **Skipped**";

  let md = `${SUMMARY_MARKER}\n`;
  md += `## 🤖 AI Code Review Summary\n\n`;
  md += `**Result:** ${statusBadge} | **Provider:** \`${result.provider}\` (\`${result.model}\`) | **Duration:** \`${(result.durationMs / 1000).toFixed(2)}s\`\n\n`;

  // Key stats table
  md += `### 📊 Overview\n\n`;
  md += `| Metric | Count |\n`;
  md += `| :--- | :--- |\n`;
  md += `| Files Analyzed | ${result.reviewedFiles.length} |\n`;
  md += `| Files Skipped | ${result.skippedFiles.length} |\n`;
  md += `| Critical Findings | ${counts.critical} |\n`;
  md += `| High Findings | ${counts.high} |\n`;
  md += `| Medium Findings | ${counts.medium} |\n`;
  md += `| Low Findings | ${counts.low} |\n`;

  if (result.usage) {
    const input = result.usage.inputTokens ?? 0;
    const output = result.usage.outputTokens ?? 0;
    const cost =
      result.usage.estimatedCost !== undefined
        ? `$${result.usage.estimatedCost.toFixed(4)}`
        : "N/A";
    md += `| Token Usage | ${input.toLocaleString()} in / ${output.toLocaleString()} out |\n`;
    md += `| Estimated Cost | ${cost} |\n`;
  }
  md += `\n`;

  // High-level summary
  md += `### 📝 Synthesis\n\n`;
  md += `${result.summary}\n\n`;

  // Blocking findings highlight
  if (result.blockingFindings.length > 0) {
    md += `### 🚫 Merge-Blocking Issues (${result.blockingFindings.length})\n\n`;
    md += `The following findings must be addressed prior to merging:\n\n`;
    for (const f of result.blockingFindings) {
      md += `- ${SEVERITY_EMOJI[f.severity]}: **[\`${f.file}\` (line ${f.line})](file://${f.file}#L${f.line})** — *${f.title}*\n`;
      md += `  > ${f.description.replace(/\n/g, "\n  > ")}\n`;
      if (f.suggestion) {
        md += `  *Suggested Fix:*\n\`\`\`suggestion\n${f.suggestion}\n\`\`\`\n`;
      }
    }
    md += `\n`;
  }

  // Findings list
  if (result.findings.length > 0) {
    md += `### 🔍 Detailed Findings (${result.findings.length})\n\n`;
    for (const f of result.findings) {
      md += `<details>\n<summary>${SEVERITY_EMOJI[f.severity]}: <b>${f.title}</b> in <code>${f.file}:${f.line}</code></summary>\n\n`;
      md += `- **File:** \`${f.file}\` (Line ${f.line})\n`;
      md += `- **Severity:** \`${f.severity}\`\n`;
      md += `- **Category:** \`${f.category}\`\n`;
      md += `- **Confidence:** \`${(f.confidence * 100).toFixed(0)}%\`\n`;
      if (f.ruleId) {
        md += `- **Custom Rule:** \`${f.ruleId}\`\n`;
      }
      md += `\n**Description:**\n${f.description}\n\n`;
      if (f.suggestion) {
        md += `**Suggested Resolution:**\n\`\`\`\n${f.suggestion}\n\`\`\`\n`;
      }
      md += `</details>\n\n`;
    }
  }

  // Unmapped findings if any
  const unmapped = options.unmappedFindings || [];
  if (unmapped.length > 0) {
    md += `### 📌 File-Level / Diff-External Findings (${unmapped.length})\n\n`;
    md += `*These findings refer to code lines outside the current diff hunks and could not be posted as inline diff comments:*\n\n`;
    for (const u of unmapped) {
      md += `- ${SEVERITY_EMOJI[u.severity]} **\`${u.file}\` (line ${u.line})**: ${u.title}\n  ${u.description}\n`;
    }
    md += `\n`;
  }

  // Skipped files
  if (result.skippedFiles.length > 0) {
    md += `<details>\n<summary>📁 Skipped Files (${result.skippedFiles.length})</summary>\n\n`;
    for (const file of result.skippedFiles) {
      md += `- \`${file}\`\n`;
    }
    md += `</details>\n\n`;
  }

  md += `---\n*Automated review generated by [@Timbaron/charlie-the-reviewer](https://github.com/Timbaron/charlie-the-reviewer)*\n`;

  return md;
}
